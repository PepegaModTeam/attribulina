#!/usr/bin/env python3
"""Writes data/messages/<game>_pc.txt: a game's Hermes messages, which
gameplay message handlers answer.

A handler's message_id is StringHash32 of the message class name
("MNotifyEscaped"). Its Lua sees the message's fields as message.<Field>; in
the debug headers those are the private members named f<Field>. The games
share the names: the editor pools every list for naming message_ids, and the
Sequence Builder offers the open game's own fields first.

Output, one message per line: the class name, then its fields as
Name:type, space separated. Lines starting with '#' are comments.

    python3 scripts/gen_messages.py [--game prostreet|carbon|undercover|mw] [header] [out]

    prostreet   nfs-data/ProStreet08Milestone.h (360 PDB dump)
    carbon      nfs-data/carbon/ps3-milestone/types_pahole.txt (pahole of the PS3 build)
    undercover  nfs-data/SpeedDebugOpt-enUS.h (Undercover's PC debug build)
    mw          exes/gamecube/mw-vanilla/NFSMWRELEASE.h (DWARF dump of Most Wanted's
                GameCube build: members without offsets). It has only the classes
                its debug info kept. Most Wanted's fields can start with a small
                letter (fhSimable): its BuildMessageTable functions give Lua
                message.hSimable.

data/messages/inferred.txt holds names no header has, found from handler
names (scripts/infer_messages.py).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GAMES = {
    "prostreet": ROOT / "nfs-data" / "ProStreet08Milestone.h",
    "carbon": ROOT / "nfs-data" / "carbon" / "ps3-milestone" / "types_pahole.txt",
    "undercover": ROOT / "nfs-data" / "SpeedDebugOpt-enUS.h",
    "mw": ROOT / "exes" / "gamecube" / "mw-vanilla" / "NFSMWRELEASE.h",
}

CLASS = re.compile(rb"^class (M[A-Za-z0-9_]*) : public Hermes::Message")
FIELD = re.compile(rb"^\s*private (.+?) f([A-Z][A-Za-z0-9_]*);")
# pahole: "struct MNotifyCollision : public Message {", members "\tint fType; /* 16 4 */"
PAHOLE_CLASS = re.compile(rb"^struct (M[A-Za-z0-9_]*) : public Message \{$")
PAHOLE_FIELD = re.compile(rb"^\t(?!extern )(.+?)\s+f([A-Z][A-Za-z0-9_]*);\s*/\*")
# DWARF dump: "struct MSpawnTraffic : Message /* size: 0x2c */  {", members "\tconst char * fVehicleName;"
DWARF_CLASS = re.compile(rb"^struct (M[A-Za-z0-9_]*) : Message /\* size: 0x[0-9a-f]+ \*/\s*\{\r?$")
DWARF_FIELD = re.compile(rb"^\t(?!inline |virtual |static )(.+?)\s+f([A-Za-z][A-Za-z0-9_]*);\r?$")


def field_type(t):
    t = re.sub(rb"\b(struct|class|enum)\s+", b"", t).strip()
    t = re.sub(rb"\s*\*", b"*", t)
    return re.sub(rb"\s+", b"_", t).decode()


def read(header, game):
    """{name: [Name:type, ...]}; a class defined more than once keeps its
    longest member list."""
    lines = header.read_bytes().split(b"\n")
    dwarf = game == "mw"
    pahole = dwarf or header.name.endswith("pahole.txt")
    cls_re, field_re = (DWARF_CLASS, DWARF_FIELD) if dwarf else (PAHOLE_CLASS, PAHOLE_FIELD) if pahole else (CLASS, FIELD)
    messages = {}
    i = 0
    while i < len(lines):
        m = cls_re.match(lines[i])
        if not m:
            i += 1
            continue
        name = m.group(1).decode()
        fields = []
        depth = 1 if pahole else 0  # pahole and the DWARF dump put the brace on the class line
        j = i + 1
        while j < len(lines):
            line = lines[j]
            depth += line.count(b"{") - line.count(b"}")
            # Members of the class itself, not of nested structs.
            if depth == 1:
                f = field_re.match(line)
                if f:
                    fields.append(f"{f.group(2).decode()}:{field_type(f.group(1))}")
            if depth <= 0 and b"};" in line:
                break
            j += 1
        if len(fields) >= len(messages.get(name, [])):
            messages[name] = fields
        i = j + 1
    return messages


def main():
    args = sys.argv[1:]
    game = "prostreet"
    if len(args) >= 2 and args[0] == "--game":
        game = args[1]
        args = args[2:]
    if game not in GAMES:
        raise SystemExit("--game is one of " + ", ".join(GAMES))
    header = Path(args[0]) if args else GAMES[game]
    out = Path(args[1]) if len(args) > 1 else ROOT / "data" / "messages" / f"{game}_pc.txt"
    messages = read(header, game)

    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", newline="\n") as fh:
        fh.write(f"# Hermes messages from {header.name} ({len(messages)}), generated by scripts/gen_messages.py\n")
        fh.write("# <class> <field>:<type> ... ; message_id = StringHash32(<class>), Lua sees message.<field>\n")
        for name in sorted(messages):
            fh.write(" ".join([name] + messages[name]) + "\n")
    print(f"{len(messages)} messages -> {out}")


if __name__ == "__main__":
    main()
