std::unique_ptr<Database> LoadFolderWithLists(const std::string& dir, const Target& t) {
    auto db = std::make_unique<Database>();
    db->setTarget(t);
    for (const auto& e : std::filesystem::directory_iterator(test::DataPath("data/schema"))) db->addTypeSchema(TypeSchema::Load(e.path().string()));
    for (const auto& e : std::filesystem::directory_iterator(test::DataPath("data/classes"))) db->addClassList(ClassList::Load(e.path().string()));
    db->names().loadFile(test::DataPath("data/attrib_keys.txt"));
    for (const FolderFile& f : FolderPacks(dir))
        if (f.skipped.empty()) {
            LoadedPack& p = db->loadPack(f.path);
            if (!f.saveAs.empty()) vaultlib::MoveToEventVaultFile(p, f.saveAs);
        }
    return db;
}

// What differs between two databases, as script statements other than the header.
size_t Differences(const Database& a, const Database& b, std::string* text = nullptr) {
    const script::Script d = script::Diff(a, b);
    size_t n = 0;
    for (const script::Statement& s : d.statements)
        n += s.kind != script::Statement::Kind::Header && s.kind != script::Statement::Kind::Meta && s.kind != script::Statement::Kind::Comment;
    if (text && n) *text = script::Print(d).substr(0, std::getenv("ATTRIB_DIFF_ALL") ? std::string::npos : 3000);
    return n;
}

